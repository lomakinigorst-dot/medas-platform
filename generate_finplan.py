# ── helpers ──────────────────────────────────────────────
def h1(text):
    p = doc.add_heading(text, level=1)
    r = p.runs[0] if p.runs else p.add_run(text)
    r.font.size = Pt(15); r.font.color.rgb = RGBColor(0x0F,0x3C,0x78)

def h2(text):
    p = doc.add_heading(text, level=2)
    r = p.runs[0] if p.runs else p.add_run(text)
    r.font.size = Pt(12); r.font.color.rgb = RGBColor(0x16,0x21,0x3E)

def h3(text):
    p = doc.add_heading(text, level=3)
    r = p.runs[0] if p.runs else p.add_run(text)
    r.font.size = Pt(10); r.font.color.rgb = RGBColor(0x0F,0x3C,0x78)

def para(text, bold=False, size=10):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(size); run.bold = bold
    p.paragraph_format.space_after = Pt(4)

def bullet(text):
    p = doc.add_paragraph(style='List Bullet')
    run = p.add_run(text)
    run.font.size = Pt(10)
    p.paragraph_format.space_after = Pt(2)

def code(text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = 'Courier New'; run.font.size = Pt(8)
    run.font.color.rgb = RGBColor(0x24,0x29,0x2E)
    p.paragraph_format.left_indent = Cm(0.5)

def tbl(headers, rows, col_widths=None):
    t = doc.add_table(rows=1+len(rows), cols=len(headers))
    t.style = 'Table Grid'
    hr = t.rows[0]
    for i,h in enumerate(headers):
        c = hr.cells[i]; c.text = h
        r = c.paragraphs[0].runs[0]
        r.bold = True; r.font.size = Pt(9)
        r.font.color.rgb = RGBColor(0xFF,0xFF,0xFF)
        shd = OxmlElement('w:shd')
        shd.set(qn('w:fill'),'1A2E6C'); shd.set(qn('w:val'),'clear')
        c._tc.get_or_add_tcPr().append(shd)
    for ri,row in enumerate(rows):
        tr = t.rows[ri+1]
        bg = 'F0F4FF' if ri%2==0 else 'FFFFFF'
        for ci,val in enumerate(row):
            c = tr.cells[ci]; c.text = val
            for r in c.paragraphs[0].runs: r.font.size = Pt(9)
            shd = OxmlElement('w:shd')
            shd.set(qn('w:fill'),bg); shd.set(qn('w:val'),'clear')
            c._tc.get_or_add_tcPr().append(shd)
    if col_widths:
        for row in t.rows:
            for i,w in enumerate(col_widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()

